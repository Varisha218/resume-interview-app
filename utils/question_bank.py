"""Smart, resume-aware interview question generation.

Parses the actual resume text to extract projects, experience, education,
achievements, and certifications, then generates deeply personalized
interview questions that reference specific details from the candidate's
background. Still entirely offline — no API calls, no fixed question bank
served regardless of input.

Every question is tagged with:
  - difficulty ("easy" | "medium" | "hard"), estimated from how specific/
    demanding the underlying prompt is (see `_estimate_difficulty`), not a
    hand-picked label.
  - concept: a short phrase describing what the answer should actually be
    about, used downstream by `transcript_analyzer` to score semantic
    relevance against what the candidate actually said (instead of relying
    only on a fixed keyword list).

The old fixed 8-question BEHAVIORAL_QUESTIONS list has been replaced by a
competency taxonomy (`COMPETENCY_TAXONOMY`): behavioral questions are
generated by combining a competency with a phrasing template, and *which*
competencies get asked is chosen based on which ones the resume doesn't
already give evidence for (via projects/roles/metrics) — so the "generic"
fallback pool still adapts to the candidate instead of being static.
"""

import re
import random


# ---------------------------------------------------------------------------
# Resume content extraction helpers
# ---------------------------------------------------------------------------

def _extract_sections(resume_text: str) -> dict:
    """Split resume text into logical sections based on common headings."""
    section_patterns = [
        r"(?i)\b(experience|work\s*experience|professional\s*experience|employment)\b",
        r"(?i)\b(projects?|personal\s*projects?|academic\s*projects?|key\s*projects?)\b",
        r"(?i)\b(education|academic\s*background|qualifications?)\b",
        r"(?i)\b(skills?|technical\s*skills?|core\s*competencies)\b",
        r"(?i)\b(certifications?|certificates?|licenses?)\b",
        r"(?i)\b(achievements?|awards?|honors?|accomplishments?)\b",
        r"(?i)\b(summary|objective|profile|about\s*me)\b",
    ]
    section_names = [
        "experience", "projects", "education", "skills",
        "certifications", "achievements", "summary",
    ]

    positions = []
    for pattern, name in zip(section_patterns, section_names):
        for m in re.finditer(pattern, resume_text):
            positions.append((m.start(), name, m.group()))
    positions.sort(key=lambda x: x[0])

    sections = {}
    for i, (pos, name, _heading) in enumerate(positions):
        end = positions[i + 1][0] if i + 1 < len(positions) else len(resume_text)
        text = resume_text[pos:end].strip()
        text = re.sub(r"^[^\n]*\n", "", text, count=1).strip()
        if text:
            sections[name] = text
    return sections


def _extract_projects(resume_text: str) -> list:
    """Extract individual project names/descriptions from the Projects section."""
    res_secs = _extract_sections(resume_text)
    proj_text = res_secs.get("projects", "")
    if not proj_text:
        return []

    projects = []
    lines = [l.strip() for l in proj_text.split("\n") if l.strip()]

    action_verbs = {
        "built", "developed", "designed", "implemented", "created", "engineered",
        "led", "managed", "optimized", "integrated", "automated", "delivered",
        "improved", "increased", "decreased", "reduced", "streamlined", "spearheaded",
        "deployed", "configured", "setup", "set", "wrote", "coded", "programmed",
        "analyzed", "researched", "tested", "debugged", "collaborated", "communicated",
        "worked", "assisted", "helped", "achieved", "using", "utilized", "utilizing", "focusing"
    }

    for i, line in enumerate(lines):
        if re.match(r"^[-•●▪\*\s]", line):
            continue

        words = line.split()
        if not words:
            continue

        first_word = words[0].lower().strip("-,. ")
        if first_word in action_verbs:
            continue

        if 2 <= len(words) <= 8 and any(w[0].isupper() for w in words if w):
            desc_lines = []
            for j in range(i + 1, len(lines)):
                if re.match(r"^[-•●▪\*\d]", lines[j]) or len(lines[j].split()) > 10:
                    desc_lines.append(lines[j].lstrip("-•●▪* ").strip())
                else:
                    break

            desc = " ".join(desc_lines)
            has_metric = bool(re.search(r"\d+%|\$\d+|\b\d{2,}\b", desc))
            projects.append({"name": line, "description": desc.strip(), "has_metric": has_metric})

    if not projects and len(lines) >= 2:
        for i, line in enumerate(lines[:3]):
            words = line.split()
            if words and words[0].lower().strip("-,. ") not in action_verbs and len(words) <= 6:
                projects.append({"name": line, "description": "", "has_metric": False})

    return projects[:5]


def _extract_roles(resume_text: str) -> list:
    """Extract job titles / roles from the Work Experience section."""
    res_secs = _extract_sections(resume_text)
    exp_text = res_secs.get("experience", "")
    if not exp_text:
        return []

    roles = set()
    role_patterns = [
        r"(?i)\b((?:senior\s+|junior\s+|lead\s+|principal\s+|staff\s+)?(?:software|data|machine learning|ml|ai|frontend|backend|full[- ]?stack|devops|cloud|mobile|web|qa|test|research|product)\s+(?:engineer|developer|scientist|analyst|architect|manager|designer|intern))\b",
        r"(?i)\b((?:project|product|program|engineering|technical)\s+(?:manager|lead|director))\b",
    ]
    for pattern in role_patterns:
        for m in re.finditer(pattern, exp_text):
            role_candidate = m.group(1).strip()
            if len(role_candidate.split()) <= 6:
                roles.add(role_candidate.title())
    return list(roles)[:3]


def _extract_companies(resume_text: str) -> list:
    """Extract company names from the Work Experience section."""
    res_secs = _extract_sections(resume_text)
    exp_text = res_secs.get("experience", "")
    if not exp_text:
        return []

    companies = set()
    lines = [l.strip() for l in exp_text.split("\n") if l.strip()]
    for line in lines:
        m1 = re.search(r"\bat\s+([A-Z][A-Za-z0-9 &.]+?)(?:\s*[,|–-]|\s*$)", line)
        if m1:
            companies.add(m1.group(1).strip())
        m2 = re.search(r"([A-Z][A-Za-z0-9 &.]{2,30})\s*(?:\|\s*[A-Z]|\(\d{4})", line)
        if m2:
            companies.add(m2.group(1).strip())

    clean_companies = []
    for c in companies:
        if c.lower() not in ("the", "a", "an", "present", "current", "experience", "work", "july", "june", "august", "september") and len(c.split()) <= 4:
            clean_companies.append(c)
    return clean_companies[:3]


def _extract_metrics(resume_text: str) -> list:
    """Extract quantified achievements (numbers, percentages, metrics) from projects/experience."""
    res_secs = _extract_sections(resume_text)
    search_blocks = []
    for key in ["experience", "projects", "achievements"]:
        if key in res_secs:
            search_blocks.append(res_secs[key])

    search_text = "\n".join(search_blocks) if search_blocks else resume_text

    metrics = []
    for line in search_text.split("\n"):
        line = line.strip()
        if re.search(r"\d+%|\$\d+|reduced|increased|improved|saved|generated|grew|boosted", line, re.IGNORECASE):
            if 15 < len(line) < 180:
                metrics.append(line.lstrip("-•●▪* ").strip())
    return metrics[:5]


def _extract_education(resume_text: str) -> list:
    """Extract education degree levels and fields from the Education section."""
    res_secs = _extract_sections(resume_text)
    edu_text = res_secs.get("education", "")
    if not edu_text:
        return []

    edu = []
    degree_patterns = [
        r"(?i)\b((?:bachelor|master|b\.?s\.?|m\.?s\.?|b\.?a\.?|m\.?a\.?|ph\.?d\.?|mba|associate|diploma|b\.?tech|m\.?tech|b\.?e\.?|m\.?e\.?)[\w\s.,]*?)(?:\n|\(|,|$)",
    ]
    for pattern in degree_patterns:
        for m in re.finditer(pattern, edu_text):
            degree = m.group(1).strip()
            if len(degree.split()) <= 8:
                edu.append(degree)
    return edu[:3]


def _extract_certifications(resume_text: str) -> list:
    """Extract professional credentials/certifications line-by-line."""
    res_secs = _extract_sections(resume_text)
    cert_text = res_secs.get("certifications", "") or res_secs.get("education", "") or resume_text

    certs = []
    lines = [l.strip() for l in cert_text.split("\n") if l.strip()]

    cert_patterns = [
        r"(?i)(aws\s+(?:certified|solutions|cloud|practitioner)[\w\s]*)",
        r"(?i)(google\s+(?:cloud|professional)[\w\s]*)",
        r"(?i)(azure[\w\s]*(?:certified|associate|expert|fundamentals)[\w\s]*)",
        r"(?i)(pmp|scrum\s*master|cissp|comptia[\w\s+]*|oracle[\w\s]*certified|pcap|capm|itil|prince2)",
        r"(?i)(certified\s+[\w\s]*)",
        r"(?i)([\w\s]*\bcertification\b[\w\s]*)",
    ]

    for line in lines:
        if line.lower().strip(":") in ("certifications", "certification", "licenses", "education", "skills", "soft skills"):
            continue
        for pattern in cert_patterns:
            m = re.search(pattern, line)
            if m:
                cert_name = m.group(1).strip()
                cert_name = re.sub(r"\s+", " ", cert_name).strip("-,. ")
                if len(cert_name.split()) >= 2 and len(cert_name.split()) <= 8:
                    certs.append(cert_name)
                    break
    return list(set(certs))[:4]


# ---------------------------------------------------------------------------
# Difficulty estimation
# ---------------------------------------------------------------------------

def _estimate_difficulty(category: str, *, has_metric: bool = False,
                          weight: float = 1.0, is_gap: bool = False) -> str:
    """Estimate a question's difficulty from what kind of demand it places
    on the candidate, rather than a hand-picked per-question label.

    Signals:
    - category: a "redesign / what would you do differently" or metrics-
      backed project question demands more depth than a plain factual one.
    - has_metric: the underlying resume line already contains a quantified
      result, so probing it further expects a precise, evidence-backed answer.
    - weight: for skill questions, reuses how heavily the JD emphasizes the
      skill — a heavily-emphasized skill warrants a harder follow-up.
    - is_gap: probing a missing skill is inherently harder to answer well
      than confirming a skill the candidate already has.
    """
    score = 0.0
    if category in ("project_redesign", "metrics"):
        score += 2.0
    elif category in ("project_architecture", "project_challenge", "skill_gap"):
        score += 1.5
    elif category in ("role", "certification", "skill_experience"):
        score += 1.0
    else:  # behavioral / education / generic
        score += 0.5

    if has_metric:
        score += 1.0
    if is_gap:
        score += 1.0
    score += min(1.0, max(0.0, (weight - 1.0) / 3.0))

    if score >= 2.5:
        return "hard"
    if score >= 1.2:
        return "medium"
    return "easy"


# ---------------------------------------------------------------------------
# Question templates — categorized by entity type for real interview flow
# ---------------------------------------------------------------------------

def _project_questions(projects: list) -> list:
    """Generate architecture, implementation, and testing questions for Projects."""
    questions = []
    templates = [
        ("project_architecture",
         "Could you walk me through the architecture and key technologies you chose for your project '{name}'?",
         ["architecture", "design", "technologies", "structure"]),
        ("project_challenge",
         "What technical challenges arose during the implementation of '{name}', and how did you resolve them?",
         ["implementation", "challenges", "technical", "issues"]),
        ("metrics",
         "How did you test, validate, or measure the performance of '{name}' to ensure it met requirements?",
         ["test", "validate", "performance", "metrics", "quality"]),
        ("project_redesign",
         "If you were to redesign your '{name}' project today, what architectural improvements would you make?",
         ["redesign", "architecture", "improvements", "scale", "performance"]),
        ("project_redesign",
         "Looking back at your '{name}' project, what would you do differently to improve scalability or performance?",
         ["differently", "scalability", "performance", "improve", "learned"]),
    ]
    for proj in projects:
        category, template, keywords = random.choice(templates)
        keywords = keywords + [w.lower() for w in proj["name"].split()[:2]]
        questions.append({
            "question": template.format(name=proj["name"]),
            "expected_keywords": keywords,
            "concept": f"the {proj['name']} project: " + " ".join(keywords[:4]),
            "category": category,
            "difficulty": _estimate_difficulty(category, has_metric=proj.get("has_metric", False)),
        })
    return questions


def _role_questions(roles: list) -> list:
    """Generate responsibility and achievement questions for Job Titles/Roles."""
    questions = []
    templates = [
        "During your tenure as a {role}, what were your primary responsibilities and the key achievements you delivered?",
        "How did you collaborate with team members and stakeholders to achieve goals as a {role}?",
        "What was a major challenge or engineering bottleneck you faced as a {role}, and what action did you take?",
    ]
    keyword_sets = [
        ["responsibilities", "achievements", "delivered", "tenure"],
        ["collaborate", "team", "stakeholders", "goals", "communication"],
        ["challenge", "bottleneck", "action", "overcome", "resolution"],
    ]
    for role in roles:
        idx = random.randrange(len(templates))
        keywords = keyword_sets[idx]
        questions.append({
            "question": templates[idx].format(role=role),
            "expected_keywords": keywords,
            "concept": f"your role as {role}: " + " ".join(keywords[:4]),
            "category": "role",
            "difficulty": _estimate_difficulty("role"),
        })
    return questions


def _metrics_questions(metrics: list) -> list:
    """Generate impact-focused questions for Achievements."""
    questions = []
    for metric_line in metrics:
        short = metric_line[:120] + ("..." if len(metric_line) > 120 else "")
        questions.append({
            "question": f"Your resume highlights: \"{short}\" — what was the business or engineering impact of this achievement, and how did you measure it?",
            "expected_keywords": ["impact", "measure", "achievement", "business", "metrics", "result"],
            "concept": f"the impact and measurement behind: {short}",
            "category": "metrics",
            "difficulty": _estimate_difficulty("metrics", has_metric=True),
        })
    return questions


def _education_questions(edu: list) -> list:
    """Generate coursework, learning, or academic project questions for Education."""
    questions = []
    for degree in edu:
        questions.append({
            "question": f"How did your academic coursework, projects, or core learnings during your {degree} shape your technical problem-solving approach?",
            "expected_keywords": ["coursework", "projects", "learnings", "academic", "problem-solving", "degree"],
            "concept": f"how your {degree} education shaped your problem-solving",
            "category": "education",
            "difficulty": _estimate_difficulty("education"),
        })
    return questions


def _certification_questions(certs: list) -> list:
    """Generate questions about applying certification knowledge."""
    questions = []
    for cert in certs:
        questions.append({
            "question": f"You hold the {cert} credential. How have you applied this specialized knowledge or best practices in your professional projects?",
            "expected_keywords": ["applied", "knowledge", "projects", "certification", "credential", "practices"],
            "concept": f"hands-on application of your {cert} certification",
            "category": "certification",
            "difficulty": _estimate_difficulty("certification"),
        })
    return questions


def _skill_experience_question(skill: str, weight: float = 1.0) -> dict:
    templates = [
        ("Can you describe a project or task where you used {skill} extensively? What was the outcome?",
         [skill, "project", "used", "outcome", "result"]),
        ("How would you rate your proficiency in {skill}, and what's the most complex thing you've built with it?",
         [skill, "proficiency", "complex", "built", "experience"]),
        ("Tell me about a time when using {skill} helped you solve a difficult problem.",
         [skill, "problem", "solved", "difficult", "approach"]),
    ]
    template, keywords = random.choice(templates)
    return {
        "question": template.format(skill=skill),
        "expected_keywords": keywords,
        "concept": f"hands-on experience with {skill}",
        "category": "skill_experience",
        "difficulty": _estimate_difficulty("skill_experience", weight=weight),
    }


def _skill_gap_question(skill: str, weight: float = 1.0) -> dict:
    templates = [
        ("This role requires experience with {skill}. What's your exposure to it, and how would you get up to speed quickly?",
         [skill, "learn", "exposure", "quickly", "approach"]),
        ("{skill} is important for this position. While it may not be on your resume, do you have any related experience?",
         [skill, "related", "experience", "similar", "learn"]),
    ]
    template, keywords = random.choice(templates)
    return {
        "question": template.format(skill=skill),
        "expected_keywords": keywords,
        "concept": f"your exposure to or plan for learning {skill}",
        "category": "skill_gap",
        "difficulty": _estimate_difficulty("skill_gap", weight=weight, is_gap=True),
    }


# ---------------------------------------------------------------------------
# Behavioral questions — generated from a competency taxonomy, not a fixed
# list. Which competencies get asked depends on which ones the resume
# doesn't already give evidence for, so two different candidates (or the
# same candidate practicing repeatedly) don't necessarily see the same set.
# ---------------------------------------------------------------------------

COMPETENCY_TAXONOMY = {
    "learning_agility": {
        "evidenced_by": {"certifications", "education"},
        "templates": [
            "Tell me about a time you had to learn a new technology or tool quickly under pressure. How did you approach it?",
            "Describe a time you had to pick up an unfamiliar skill on your own with no formal training available.",
        ],
        "keywords": ["learn", "technology", "pressure", "approach", "quickly"],
    },
    "conflict_resolution": {
        "evidenced_by": {"roles"},
        "templates": [
            "Describe a situation where you disagreed with a team member's technical decision. How did you resolve it?",
            "Tell me about a disagreement you had with a teammate or manager, and how it was resolved.",
        ],
        "keywords": ["disagree", "team", "resolved", "communication", "compromise"],
    },
    "failure_recovery": {
        "evidenced_by": {"metrics"},
        "templates": [
            "Tell me about a project that failed or didn't meet expectations. What did you learn from it?",
            "Describe a time a decision you made turned out to be wrong. What did you do next?",
        ],
        "keywords": ["failed", "learned", "improve", "mistake", "takeaway"],
    },
    "time_management": {
        "evidenced_by": {"roles", "projects"},
        "templates": [
            "How do you prioritize tasks when you have multiple deadlines competing for your attention?",
            "Tell me about a time you had to juggle several competing priorities at once.",
        ],
        "keywords": ["prioritize", "deadline", "manage", "organize", "time"],
    },
    "initiative": {
        "evidenced_by": {"projects", "metrics"},
        "templates": [
            "Describe a time you went above and beyond what was expected of you.",
            "Tell me about something you built or improved that nobody asked you to do.",
        ],
        "keywords": ["beyond", "initiative", "extra", "impact", "result"],
    },
    "motivation": {
        "evidenced_by": set(),
        "templates": [
            "What motivates you in your work, and how do you stay productive during challenging periods?",
        ],
        "keywords": ["motivate", "productive", "challenge", "drive", "passion"],
    },
    "feedback_handling": {
        "evidenced_by": {"roles"},
        "templates": [
            "Tell me about a time you received critical feedback. How did you respond and what changed?",
        ],
        "keywords": ["feedback", "respond", "changed", "improved", "growth"],
    },
    "problem_solving": {
        "evidenced_by": {"projects"},
        "templates": [
            "How do you approach debugging a complex issue that you've never encountered before?",
            "Walk me through how you break down a problem you don't immediately know how to solve.",
        ],
        "keywords": ["debug", "approach", "systematic", "research", "solve"],
    },
}


def _generate_behavioral_questions(evidence_present: set, n: int) -> list:
    """Pick `n` competencies to probe, prioritizing ones the resume doesn't
    already give supporting evidence for, and generate a question for each
    from its template pool.
    """
    competencies = list(COMPETENCY_TAXONOMY.items())

    def uncovered_first(item):
        name, spec = item
        overlap = len(spec["evidenced_by"] & evidence_present)
        return (overlap, random.random())

    competencies.sort(key=uncovered_first)

    questions = []
    for name, spec in competencies[:n]:
        template = random.choice(spec["templates"])
        questions.append({
            "question": template,
            "expected_keywords": spec["keywords"],
            "concept": f"{name.replace('_', ' ')}: " + " ".join(spec["keywords"][:4]),
            "category": "behavioral",
            "difficulty": _estimate_difficulty("behavioral"),
        })
    return questions


# ---------------------------------------------------------------------------
# Pool builder — the shared entry point used by the adaptive engine
# ---------------------------------------------------------------------------

def generate_question_pool(matched_skills, missing_skills, resume_text: str = "",
                            skill_weights: dict = None) -> dict:
    """Build a full, resume-and-JD-aware question pool, tiered by difficulty.

    Returns {"easy": [...], "medium": [...], "hard": [...]}, each item a
    dict with question/expected_keywords/concept/category/difficulty. The
    adaptive engine (see utils/adaptive_engine.py) draws from this pool
    question-by-question based on live performance instead of the whole set
    being decided up front.
    """
    skill_weights = skill_weights or {}
    all_questions = []
    evidence_present = set()

    if resume_text:
        projects = _extract_projects(resume_text)
        roles = _extract_roles(resume_text)
        metrics = _extract_metrics(resume_text)
        education = _extract_education(resume_text)
        certs = _extract_certifications(resume_text)

        if projects:
            evidence_present.add("projects")
            all_questions.extend(_project_questions(projects))
        if roles:
            evidence_present.add("roles")
            all_questions.extend(_role_questions(roles))
        if metrics:
            evidence_present.add("metrics")
            all_questions.extend(_metrics_questions(metrics))
        if education:
            evidence_present.add("education")
            all_questions.extend(_education_questions(education))
        if certs:
            evidence_present.add("certifications")
            all_questions.extend(_certification_questions(certs))

    for skill in matched_skills:
        weight = skill_weights.get(skill, 1.0)
        all_questions.append(_skill_experience_question(skill, weight=weight))
    for skill in missing_skills:
        weight = skill_weights.get(skill, 1.0)
        all_questions.append(_skill_gap_question(skill, weight=weight))

    all_questions.extend(_generate_behavioral_questions(evidence_present, n=len(COMPETENCY_TAXONOMY)))

    pool = {"easy": [], "medium": [], "hard": []}
    for q in all_questions:
        pool[q["difficulty"]].append(q)

    for tier in pool:
        random.shuffle(pool[tier])
        for i, q in enumerate(pool[tier]):
            # Stable id so the client can round-trip the pool and the server
            # can track which questions have already been asked.
            q["_id"] = f"{tier}-{i}"

    return pool


def generate_questions(matched_skills, missing_skills, mode: str = "practice",
                        count: int = 6, resume_text: str = ""):
    """Backward-compatible flat list builder. Prefer `generate_question_pool`
    combined with utils.adaptive_engine for the live interview modes.
    """
    pool = generate_question_pool(matched_skills, missing_skills, resume_text)
    ordered = pool["medium"] + pool["hard"] + pool["easy"]
    random.shuffle(ordered)
    questions = ordered[:count]
    random.shuffle(questions)

    total_seconds = 6.5 * 60 if mode == "mock" else 8 * 60
    per_question_seconds = int(total_seconds / max(1, len(questions)))

    for i, q in enumerate(questions):
        q["id"] = i + 1
        q["time_limit_seconds"] = per_question_seconds

    return questions
